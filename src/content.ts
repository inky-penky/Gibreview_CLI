import type { Batch, TestPlan } from './plan.js';
import { poolPerBatch } from './plan.js';
import { qaTemplate } from './parser.js';
import { renderTemplate } from './template.js';

export { htmlToText } from './template.js';

const esc = (s: string) =>
  s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

export function bountyTitle(plan: TestPlan, batch: Batch): string {
  const device = plan.devices.find((d) => d.id === batch.deviceId)!;
  const part = batch.parts > 1 ? ` (part ${batch.part}/${batch.parts})` : '';
  const release = plan.release ? ` ${plan.release}` : '';
  return `[QA] ${plan.name}${release} on ${device.label}${part}`.slice(0, 120);
}

/** The block testers paste back. The parser keys off these exact case ids. */
export function resultTemplate(batch: Batch): string {
  return renderTemplate(qaTemplate(batch.caseIds));
}

export function bountyContent(plan: TestPlan, batch: Batch, runId: string): string {
  const device = plan.devices.find((d) => d.id === batch.deviceId)!;
  const cases = batch.caseIds.map((id) => plan.cases.find((c) => c.id === id)!);
  const parts: string[] = [];

  parts.push(
    `<p>Run ${cases.length} manual test case${cases.length === 1 ? '' : 's'} on a real <strong>${esc(device.label)}</strong> device and report the result of each one in the format below.</p>`,
  );
  parts.push('<h3>Build under test</h3>');
  parts.push(`<p><a href="${esc(plan.build.url)}">${esc(plan.build.url)}</a>${plan.release ? ` (release ${esc(plan.release)})` : ''}</p>`);
  if (plan.build.notes) parts.push(`<p>${esc(plan.build.notes)}</p>`);
  if (device.notes) parts.push(`<p><strong>Device notes:</strong> ${esc(device.notes)}</p>`);

  parts.push('<h3>Test cases</h3>');
  for (const c of cases) {
    parts.push(`<h4>${esc(c.id)}. ${esc(c.title)} [${c.priority}]</h4>`);
    if (c.preconditions) parts.push(`<p><em>Before you start:</em> ${esc(c.preconditions)}</p>`);
    parts.push(`<ol>${c.steps.map((s) => `<li>${esc(s)}</li>`).join('')}</ol>`);
    parts.push(`<p><strong>Expected:</strong> ${esc(c.expected)}</p>`);
  }

  parts.push('<h3>How to submit</h3>');
  parts.push(
    '<p>Paste this block into your submission and fill in every line. Pick exactly one of PASS, FAIL or BLOCKED per case. ' +
      'Every FAIL needs a short description and a link to a screenshot or screen recording. Submissions that skip cases or have no evidence for failures are not paid.</p>',
  );
  parts.push(`<pre>${esc(resultTemplate(batch))}</pre>`);
  parts.push(
    `<p>Reward is ${esc(plan.reward.perTester)} ${esc(plan.reward.symbol)} per accepted tester, up to ${plan.reward.testersPerBatch} testers (pool ${poolPerBatch(plan)} ${esc(plan.reward.symbol)}).</p>`,
  );
  parts.push(`<p><small>Ref ${esc(runId)}/${esc(batch.id)}. Generated by gibreview.</small></p>`);
  return parts.join('\n');
}
