import { writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { stringify } from 'yaml';
import { validatePlan, type TestPlan } from '../plan.js';
import { loadPage, type PageModel, type RenderMode } from './extract.js';
import { rulesCases, type DraftCase } from './rules.js';
import { aiCases } from './ai.js';

export interface GenerateOptions {
  url: string;
  htmlFile?: string;
  render?: RenderMode;
  cookies?: string;
  describe?: string;
  name?: string;
  maxCases?: number;
  /** 'auto' uses AI when ANTHROPIC_API_KEY is set. */
  ai?: 'auto' | 'on' | 'off';
  model?: string;
  log?: (m: string) => void;
}

export interface GenerateResult {
  plan: TestPlan;
  page: PageModel;
  source: 'rules' | 'ai';
  warnings: string[];
  yaml: string;
}

const RANK = { high: 0, medium: 1, low: 2 } as const;

/** Keeps the most important cases when trimming to maxCases, but preserves the original order. */
function cap(cases: DraftCase[], max: number): DraftCase[] {
  if (cases.length <= max) return cases;
  const keep = new Set(
    cases
      .map((c, i) => ({ c, i }))
      .sort((a, b) => RANK[a.c.priority] - RANK[b.c.priority] || a.i - b.i)
      .slice(0, max)
      .map((x) => x.i),
  );
  return cases.filter((_, i) => keep.has(i));
}

export async function generatePlan(opts: GenerateOptions): Promise<GenerateResult> {
  const log = opts.log ?? (() => {});
  const warnings: string[] = [];
  const maxCases = opts.maxCases ?? 12;

  const page = await loadPage({ url: opts.url, htmlFile: opts.htmlFile, render: opts.render, cookies: opts.cookies, log });
  if (page.renderedWith === 'fetch') warnings.push('Page was read without a browser. If it is built with JavaScript, install Playwright for a complete picture.');
  if (!page.forms.length && !page.actions.length) warnings.push('No forms or buttons were found. The page may need a login (--cookies) or a browser (--render browser).');

  const baseline = rulesCases(page);
  let drafts: DraftCase[] = baseline;
  let source: GenerateResult['source'] = 'rules';

  const apiKey = process.env.ANTHROPIC_API_KEY;
  const wantAi = opts.ai === 'on' || (opts.ai !== 'off' && !!apiKey);
  if (wantAi) {
    if (!apiKey) throw new Error('--ai needs ANTHROPIC_API_KEY in the environment');
    log('Asking the AI writer to refine the cases…');
    try {
      drafts = await aiCases(page, baseline, { apiKey, model: opts.model, maxCases, describe: opts.describe });
      source = 'ai';
    } catch (err) {
      warnings.push(`AI generation failed, used rule-based cases instead (${(err as Error).message})`);
    }
  } else if (opts.describe) {
    warnings.push('--describe is only used by the AI writer. Set ANTHROPIC_API_KEY to use it.');
  }

  drafts = cap(drafts, maxCases);
  const host = (() => {
    try {
      return new URL(opts.url).hostname;
    } catch {
      return 'feature';
    }
  })();
  const name = opts.name ?? `${page.title.split(/[·|–-]/)[0].trim() || host} test pass`;

  const raw = {
    name,
    draft: true,
    build: { url: opts.url, notes: 'Add test logins, test card details and anything else testers need here.' },
    reward: { symbol: 'USDC', perTester: '2.00', testersPerBatch: 2 },
    batchSize: 5,
    deadlineHours: 48,
    tags: ['QA', 'Testing'],
    gate: { failOn: ['high'], requireCoverageOn: ['high'] },
    devices: [
      { id: 'android-chrome', label: 'Android phone (Chrome)' },
      { id: 'ios-safari', label: 'iPhone (Safari)' },
      { id: 'desktop', label: 'Desktop browser' },
    ],
    cases: drafts.map((c, i) => ({
      id: `TC-${String(i + 1).padStart(2, '0')}`,
      title: c.title.slice(0, 100),
      priority: c.priority,
      ...(c.preconditions ? { preconditions: c.preconditions } : {}),
      steps: c.steps,
      expected: c.expected,
      ...(c.devices?.length ? { devices: c.devices } : {}),
      source,
      ...(c.reviewNote ? { reviewNote: c.reviewNote } : {}),
    })),
  };
  const plan = validatePlan(raw);

  const header = [
    `# Generated by "bugbash generate" from ${opts.url}`,
    `# ${new Date().toISOString()} · ${source === 'ai' ? 'AI writer' : 'rule-based writer'} · page read via ${page.renderedWith}`,
    '#',
    '# This is a DRAFT. Before paying testers to run it:',
    '#   1. Read every case. Fix steps and expected results to match how the feature should behave.',
    '#   2. Resolve each reviewNote, then delete the reviewNote line.',
    '#   3. Add test logins and payment details to build.notes, and set the reward.',
    '#   4. Delete "draft: true". Only then will "bugbash plan" accept this file.',
    '',
  ].join('\n');
  const yaml = header + stringify(raw, { lineWidth: 110 });
  return { plan, page, source, warnings, yaml };
}

export async function writePlanFile(path: string, yaml: string, force = false) {
  if (existsSync(path) && !force) throw new Error(`${path} already exists. Use --force to overwrite.`);
  await writeFile(path, yaml);
}
