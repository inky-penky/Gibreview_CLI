import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import type { RunState } from './state.js';
import type { Aggregate, CellOutcome } from './aggregate.js';

const ICON: Record<CellOutcome, string> = { PASS: '✅ pass', FAIL: '❌ fail', DISPUTED: '⚠️ disputed', BLOCKED: '⛔ blocked', NOT_RUN: '— not run' };

const xml = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const csv = (s: string | number | null | undefined) => {
  const v = String(s ?? '');
  return /[",\n]/.test(v) ? `"${v.replace(/"/g, '""')}"` : v;
};
const md = (s: string) => s.replace(/\|/g, '\\|');

/** Submissions left out of the matrix that a person should know about. Shared by the Markdown report and the CLI. */
export function attentionNotes(agg: Aggregate): string[] {
  const notes: string[] = [];
  const n = agg.totals.awaitingTriage;
  if (n) notes.push(`${n} incomplete submission${n === 1 ? ' is' : 's are'} waiting for triage and not counted in the results. Run triage to settle ${n === 1 ? 'it' : 'them'}.`);
  const o = agg.totals.needsAttention;
  if (o) notes.push(`${o} submission${o === 1 ? ' has' : 's have'} a Gibwork status gibreview does not recognise. Check ${o === 1 ? 'it' : 'them'} on Gibwork (see the tester ledger).`);
  return notes;
}

export function renderMarkdown(run: RunState, agg: Aggregate): string {
  const { plan } = run;
  const out: string[] = [];
  const verdictLine = { PASS: '✅ PASS, safe to release', FAIL: '❌ FAIL, release blocked', INCOMPLETE: '⚠️ INCOMPLETE, coverage gaps on required cases' }[agg.gate.verdict];

  out.push(`# QA report · ${plan.name}${plan.release ? ` ${plan.release}` : ''}`);
  out.push('');
  out.push(`Run \`${run.runId}\` · environment **${run.environment}** · generated ${new Date().toISOString()}`);
  out.push(`Build under test ${plan.build.url}`);
  out.push('');
  out.push(`## Release gate ${verdictLine}`);
  out.push('');
  for (const r of agg.gate.reasons) out.push(`- ${r}`);
  out.push('');
  out.push(
    `Testers submitted **${agg.totals.submissions}** results, ${agg.totals.valid} valid, ${agg.totals.incomplete} incomplete, ${agg.totals.invalid} invalid. ` +
      `${agg.totals.approved} approved, ${agg.totals.rejected} rejected, **${agg.totals.paid} ${plan.reward.symbol}** paid out.`,
  );
  out.push('');
  for (const note of attentionNotes(agg)) out.push(`> ${note}`, '');

  out.push('## Results matrix');
  out.push('');
  out.push(`| Case | Priority | ${plan.devices.map((d) => md(d.label)).join(' | ')} |`);
  out.push(`| --- | --- | ${plan.devices.map(() => '---').join(' | ')} |`);
  for (const c of agg.cases) {
    const cols = plan.devices.map((d) => {
      const cell = c.cells.find((x) => x.deviceId === d.id);
      if (!cell) return 'n/a';
      const n = cell.pass + cell.fail + cell.blocked;
      return `${ICON[cell.outcome]}${n ? ` (${n})` : ''}`;
    });
    out.push(`| ${md(c.testCase.id)} ${md(c.testCase.title)} | ${c.testCase.priority} | ${cols.join(' | ')} |`);
  }
  out.push('');

  const problems = agg.cases.flatMap((c) => c.cells.filter((x) => x.outcome === 'FAIL' || x.outcome === 'DISPUTED' || x.outcome === 'BLOCKED').map((cell) => ({ c, cell })));
  if (problems.length) {
    out.push('## Failures and blockers');
    out.push('');
    for (const { c, cell } of problems) {
      const device = plan.devices.find((d) => d.id === cell.deviceId)!.label;
      out.push(`### ${c.testCase.id} ${c.testCase.title} on ${device} (${cell.outcome.toLowerCase()})`);
      out.push('');
      out.push(`Expected ${c.testCase.expected}`);
      out.push('');
      for (const o of cell.observations.filter((x) => x.status !== 'PASS' || cell.outcome === 'DISPUTED')) {
        const ev = o.evidence.length ? ` · evidence ${o.evidence.join(', ')}` : '';
        out.push(`- **${o.status}** by @${o.username} (${o.device ?? 'unknown device'})${o.note ? `. ${o.note}` : ''}${ev}`);
      }
      out.push('');
    }
  }

  out.push('## Tester ledger');
  out.push('');
  out.push('| Tester | Bounty | Device | Parse verdict | Review | Payout | Notes |');
  out.push('| --- | --- | --- | --- | --- | --- | --- |');
  for (const s of Object.values(run.submissions).sort((a, b) => a.batchId.localeCompare(b.batchId) || a.createdAt.localeCompare(b.createdAt))) {
    const payout = s.decision?.action === 'approve' ? `${s.decision.amount} ${plan.reward.symbol}` : '';
    out.push(`| @${md(s.username)} | ${s.batchId} | ${md(s.parsed.device ?? '')} | ${s.parsed.verdict} | ${s.reviewStatus === 'other' ? `other (${md(s.remoteStatus ?? 'unknown')})` : s.reviewStatus} | ${payout} | ${md(s.parsed.issues.join('; '))} |`);
  }
  out.push('');

  out.push('## Bounties');
  out.push('');
  for (const b of run.batches) {
    out.push(`- \`${b.id}\` ${b.title} · ${b.caseIds.length} cases · task ${b.taskId ?? 'not published'}${b.txHash ? ` · tx ${b.txHash}` : ''}`);
  }
  out.push('');
  out.push('Generated by gibreview using the Gibwork SDK.');
  return out.join('\n');
}

export function renderCsv(run: RunState): string {
  const rows = [['run_id', 'batch_id', 'device_id', 'task_id', 'submission_id', 'tester', 'tester_device', 'parse_verdict', 'review_status', 'case_id', 'priority', 'status', 'note', 'evidence']];
  for (const s of Object.values(run.submissions)) {
    const batch = run.batches.find((b) => b.id === s.batchId)!;
    const results = s.parsed.results.length ? s.parsed.results : [null];
    for (const r of results) {
      const tc = r ? run.plan.cases.find((c) => c.id === r.caseId) : undefined;
      rows.push([run.runId, s.batchId, batch.deviceId, s.taskId, s.id, s.username, s.parsed.device ?? '', s.parsed.verdict, s.reviewStatus, r?.caseId ?? '', tc?.priority ?? '', r?.status ?? '', r?.note ?? '', r?.evidence.join(' ') ?? '']);
    }
  }
  return rows.map((r) => r.map(csv).join(',')).join('\n') + '\n';
}

/** JUnit XML so crowd results show up in GitHub Actions, GitLab, Jenkins and friends like any other test suite. */
export function renderJUnit(run: RunState, agg: Aggregate): string {
  const lines: string[] = ['<?xml version="1.0" encoding="UTF-8"?>'];
  const all = agg.cases.flatMap((c) => c.cells);
  const failures = all.filter((c) => c.outcome === 'FAIL' || c.outcome === 'DISPUTED').length;
  const skipped = all.filter((c) => c.outcome === 'BLOCKED' || c.outcome === 'NOT_RUN').length;
  lines.push(`<testsuites name="${xml(run.plan.name)}" tests="${all.length}" failures="${failures}" skipped="${skipped}">`);
  for (const device of run.plan.devices) {
    const cells = agg.cases.flatMap((c) => c.cells.filter((x) => x.deviceId === device.id).map((cell) => ({ c, cell })));
    if (!cells.length) continue;
    const f = cells.filter(({ cell }) => cell.outcome === 'FAIL' || cell.outcome === 'DISPUTED').length;
    const s = cells.filter(({ cell }) => cell.outcome === 'BLOCKED' || cell.outcome === 'NOT_RUN').length;
    lines.push(`  <testsuite name="${xml(device.label)}" tests="${cells.length}" failures="${f}" skipped="${s}">`);
    for (const { c, cell } of cells) {
      const name = `${c.testCase.id} ${c.testCase.title}`;
      lines.push(`    <testcase classname="gibreview.qa.${xml(device.id)}" name="${xml(name)}">`);
      lines.push(`      <properties><property name="priority" value="${c.testCase.priority}"/><property name="observations" value="${cell.pass + cell.fail + cell.blocked}"/></properties>`);
      const detail = cell.observations
        .map((o) => `${o.status} by @${o.username} (${o.device ?? 'unknown device'})${o.note ? `: ${o.note}` : ''}${o.evidence.length ? ` [${o.evidence.join(' ')}]` : ''}`)
        .join('\n');
      if (cell.outcome === 'FAIL' || cell.outcome === 'DISPUTED') {
        lines.push(`      <failure message="${cell.outcome === 'FAIL' ? 'Failed' : 'Disputed'} on ${xml(device.label)} (${cell.fail} fail, ${cell.pass} pass)">${xml(detail)}</failure>`);
      } else if (cell.outcome === 'BLOCKED' || cell.outcome === 'NOT_RUN') {
        lines.push(`      <skipped message="${cell.outcome === 'BLOCKED' ? 'Blocked' : 'No tester result yet'}"/>`);
      }
      if (detail && cell.outcome === 'PASS') lines.push(`      <system-out>${xml(detail)}</system-out>`);
      lines.push('    </testcase>');
    }
    lines.push('  </testsuite>');
  }
  lines.push('</testsuites>');
  return lines.join('\n') + '\n';
}

export type ReportFormat = 'md' | 'csv' | 'junit' | 'json';

export async function writeReports(run: RunState, agg: Aggregate, outDir: string, formats: ReportFormat[]): Promise<string[]> {
  await mkdir(outDir, { recursive: true });
  const written: string[] = [];
  const put = async (name: string, body: string) => {
    const p = join(outDir, name);
    await writeFile(p, body);
    written.push(p);
  };
  if (formats.includes('md')) await put('report.md', renderMarkdown(run, agg));
  if (formats.includes('csv')) await put('results.csv', renderCsv(run));
  if (formats.includes('junit')) await put('junit.xml', renderJUnit(run, agg));
  if (formats.includes('json')) await put('summary.json', JSON.stringify({ runId: run.runId, gate: agg.gate, totals: agg.totals, cases: agg.cases.map((c) => ({ id: c.testCase.id, priority: c.testCase.priority, outcome: c.outcome, cells: c.cells.map(({ observations, ...rest }) => rest) })) }, null, 2) + '\n');
  return written;
}
